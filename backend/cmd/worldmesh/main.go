// Command worldmesh renders the world's terrain, caves included, to the mesh the booth's 3D map
// draws. A heightmap cannot represent caves: many columns have more than one solid layer.
//
//	go run ./cmd/worldmesh                       # writes internal/web/static/map/worldmesh.bin.gz
//	go run ./cmd/worldmesh -cell 8               # coarser, smaller, faster
//
// The output is gzipped (about 14 MiB from 36 MiB); the browser decompresses it with
// DecompressionStream. It needs a Subnautica install, so it is not in the container image, but its
// output is embedded in the binary. Only the booth reads it, hence `internal/web/static/map/`.
package main

import (
	"bufio"
	"compress/gzip"
	"encoding/binary"
	"encoding/json"
	"flag"
	"fmt"
	"math"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/caesarakalaeii/subnautica-creator-royale/backend/internal/world"
)

// positionScale is file units per metre: eighths, so positions fit in int16 at 0.125 m precision.
const positionScale = 8

// magic is the file's first eight bytes; the version is part of it, so a wrong version is refused.
const magic = "LMSMESH1"

func main() {
	install := flag.String("install", defaultInstall(), "a Subnautica install")
	// 4 m is the resolution of the committed asset, so it is the default.
	cell := flag.Int("cell", 4, "grid resolution in metres")
	minY := flag.Int("min-y", -1920, "lowest elevation to draw")
	maxY := flag.Int("max-y", 160, "highest elevation to draw")
	iso := flag.Float64("iso", 0.5, "the occupancy fraction that counts as rock")
	smooth := flag.Int("smooth", 1, "blur passes over the field before surfacing it")
	output := flag.String("output", "internal/web/static/map/worldmesh.bin.gz", "where to write the mesh")
	stats := flag.Bool("stats", false, "report where the surface is by depth, and write nothing")
	flag.Parse()

	if *stats {
		if err := report(*install, *cell, *minY, *maxY, float32(*iso)); err != nil {
			fmt.Fprintf(os.Stderr, "worldmesh: %v\n", err)
			os.Exit(1)
		}

		return
	}

	if err := run(*install, *cell, *minY, *maxY, float32(*iso), *smooth, *output); err != nil {
		fmt.Fprintf(os.Stderr, "worldmesh: %v\n", err)
		os.Exit(1)
	}
}

func defaultInstall() string {
	if fromEnv := os.Getenv("SUBNAUTICA_INSTALLATION_PATH"); fromEnv != "" {
		return fromEnv
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return ""
	}

	return filepath.Join(home, ".local/share/Steam/steamapps/common/Subnautica")
}

func run(install string, cell, minY, maxY int, iso float32, smooth int, output string) error {
	terrain, err := world.Open(install)
	if err != nil {
		return err
	}

	started := time.Now()
	grid := world.NewGrid(cell, minY, maxY)
	fmt.Fprintf(os.Stderr, "field %dx%dx%d at %d m, %d cells\n",
		grid.NX, grid.NY, grid.NZ, cell, grid.NX*grid.NY*grid.NZ)

	if err := grid.Fill(terrain, func(done, total int) {
		fmt.Fprintf(os.Stderr, "\r  reading octrees %d/%d batches", done, total)
	}); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "\r  read the octrees in %.0fs\n", time.Since(started).Seconds())

	if smooth > 0 {
		blurring := time.Now()
		grid.Smooth(smooth)
		fmt.Fprintf(os.Stderr, "  smoothed %d pass(es) in %.0fs\n", smooth, time.Since(blurring).Seconds())
	}

	surfacing := time.Now()
	mesh := world.SurfaceNets(grid, iso)
	fmt.Fprintf(os.Stderr, "  surfaced in %.0fs: %d vertices, %d triangles\n",
		time.Since(surfacing).Seconds(), mesh.Vertices(), mesh.Triangles())

	if mesh.Vertices() == 0 {
		return fmt.Errorf("the mesh is empty, which means the field is: is %s an install?", install)
	}
	if mesh.Vertices() > 1<<31 {
		return fmt.Errorf("%d vertices overflows the 32-bit indices in the format", mesh.Vertices())
	}

	if err := write(output, mesh); err != nil {
		return err
	}

	meta := map[string]any{
		"_comment": "Generated by backend/cmd/worldmesh. The renderer reads this rather than " +
			"hard-coding the format.",
		"magic":         magic,
		"positionScale": positionScale,
		"cellMetres":    cell,
		"minY":          minY,
		"maxY":          maxY,
		"iso":           iso,
		"smoothPasses":  smooth,
		"vertices":      mesh.Vertices(),
		"triangles":     mesh.Triangles(),
		"gzipped":       true,
		"worldMetres":   world.WorldX,
	}
	metaPath := strings.TrimSuffix(strings.TrimSuffix(output, ".gz"), ".bin") + ".json"
	encoded, err := json.MarshalIndent(meta, "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Clean(metaPath), append(encoded, '\n'), 0o644); err != nil {
		return err
	}

	info, err := os.Stat(filepath.Clean(output))
	if err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "%s  %.1f MiB\n%s  the format the renderer is tested against\n",
		output, float64(info.Size())/(1<<20), metaPath)

	return nil
}

// write puts the mesh on disk gzipped: a header, quantised positions, then 32-bit indices. Whole
// slices go through binary.Write at once, since per-value calls are far slower at this size.
func write(path string, mesh *world.Mesh) error {
	file, err := os.Create(filepath.Clean(path))
	if err != nil {
		return err
	}
	defer file.Close()

	compressor, err := gzip.NewWriterLevel(file, gzip.BestCompression)
	if err != nil {
		return err
	}
	defer compressor.Close()

	buffered := bufio.NewWriterSize(compressor, 1<<20)

	if _, err := buffered.WriteString(magic); err != nil {
		return err
	}
	header := []uint32{uint32(mesh.Vertices()), uint32(len(mesh.Indices))}
	if err := binary.Write(buffered, binary.LittleEndian, header); err != nil {
		return err
	}

	quantised := make([]int16, len(mesh.Positions))
	for i, metres := range mesh.Positions {
		quantised[i] = int16(math.Round(float64(metres) * positionScale))
	}
	if err := binary.Write(buffered, binary.LittleEndian, quantised); err != nil {
		return err
	}

	// Pad the positions to a four-byte boundary before the indices: the browser reads the indices
	// as a Uint32Array view over the same buffer, which must start on a multiple of four bytes.
	if padding := (4 - (len(quantised)*2)%4) % 4; padding > 0 {
		if _, err := buffered.Write(make([]byte, padding)); err != nil {
			return err
		}
	}
	if err := binary.Write(buffered, binary.LittleEndian, mesh.Indices); err != nil {
		return err
	}

	if err := buffered.Flush(); err != nil {
		return err
	}

	return compressor.Close()
}

// report prints how the surface is distributed by depth, without building a mesh, to judge what a
// grid resolution would cost.
func report(install string, cell, minY, maxY int, iso float32) error {
	terrain, err := world.Open(install)
	if err != nil {
		return err
	}

	grid := world.NewGrid(cell, minY, maxY)
	if err := grid.Fill(terrain, nil); err != nil {
		return err
	}

	const band = 200
	cells := map[int]int{}
	total := 0
	for j := 0; j < grid.NY-1; j++ {
		_, y, _ := grid.Centre(0, j, 0)
		for k := 0; k < grid.NZ-1; k++ {
			for i := 0; i < grid.NX-1; i++ {
				inside, outside := 0, 0
				for c := 0; c < 8; c++ {
					if grid.Fraction(i+c&1, j+(c>>1)&1, k+(c>>2)&1) >= iso {
						inside++
					} else {
						outside++
					}
				}
				if inside > 0 && outside > 0 {
					// Floor, not truncate: integer division rounds toward zero, which would mislabel negative
					// bands.
					cells[int(math.Floor(float64(y)/band))*band]++
					total++
				}
			}
		}
	}

	fmt.Printf("%d surface cells at %d m\n", total, cell)
	for y := maxY / band * band; y >= minY; y -= band {
		if n, ok := cells[y]; ok {
			fmt.Printf("  %6d..%6d m  %9d  %5.1f%%\n", y, y+band, n, 100*float64(n)/float64(total))
		}
	}

	return nil
}
